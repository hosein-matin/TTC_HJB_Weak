"""Train MSE and stopped-step-regularized candidates (requires PyTorch).

The supplied checkpoints were trained for 100 epochs on rounded-time data
with impact-boundary supervision.  They are not retrained by the revised
evaluation.  Newly generated datasets preserve continuous start times by
default; their data_protocol.json is copied into new checkpoint metadata.
Use --terminal-boundary to add the finite-horizon zero boundary explicitly
when training a new candidate on the terminal-absorbing extension.
"""
from pathlib import Path
import argparse, time, json, numpy as np, torch, torch.nn as nn
import ttc as T

torch.set_num_threads(2)
torch.manual_seed(0)
H = 0.05            # step of the stopped-step operator used in the loss
LAM_S = 1.0
WIDTH, DEPTH = 400, 3
EPOCHS, BATCH, LR = 100, 4096, 1e-3
LO = np.array([T.BOX["s"][0], T.BOX["Xi"][0], T.BOX["Lam"][0], T.BOX["zeta"][0]], np.float32)
HI = np.array([T.BOX["s"][1], T.BOX["Xi"][1], T.BOX["Lam"][1], T.BOX["zeta"][1]], np.float32)


def norm(z):
    return 2 * (z - LO) / (HI - LO) - 1


class MLP(nn.Module):
    def __init__(self):
        super().__init__()
        layers, d = [], 4
        for _ in range(DEPTH):
            layers += [nn.Linear(d, WIDTH), nn.ReLU()]
            d = WIDTH
        layers += [nn.Linear(d, 1)]
        self.net = nn.Sequential(*layers)

    def forward(self, z):
        return self.net(z).squeeze(-1)


def load(name, data_dir=Path("out"), terminal_boundary=False):
    d = np.load(data_dir / f"data_{name}.npz")
    z = np.concatenate([d["s"][:, None], d["y"]], 1).astype(np.float32)
    V = d["V"].astype(np.float32)
    ell = np.minimum(H, V).astype(np.float32)
    zl = np.concatenate([(d["s"] + ell)[:, None], d[f"snap_{H}"]], 1).astype(np.float32)
    # boundary samples: impact points, target 0
    hit = d["hit"]
    zb = np.concatenate([(d["s"] + V)[hit][:, None], d["y_imp"][hit]], 1).astype(np.float32)
    if terminal_boundary:
        if "y_final" not in d:
            raise ValueError("Terminal supervision requires data generated by the revised gen_data.py")
        terminal = np.concatenate([np.full((np.count_nonzero(~hit), 1), T.TH),
                                   d["y_final"][~hit]], 1).astype(np.float32)
        zb = np.concatenate([zb, terminal])
    d.close()
    return z, V, ell, zl, zb


def run(tag, lam_s, data_dir=Path("out"), out_dir=Path("out"), terminal_boundary=False):
    out_dir.mkdir(parents=True, exist_ok=True)
    z, V, ell, zl, zb = load("train", data_dir, terminal_boundary)
    zv, Vv, *_ = load("val", data_dir)
    # append boundary samples (target 0, residual term inactive) to the regression set
    zall = np.concatenate([z, zb]); Vall = np.concatenate([V, np.zeros(len(zb), np.float32)])
    mask_res = np.concatenate([np.ones(len(z), bool), np.zeros(len(zb), bool)])
    ell_all = np.concatenate([ell, np.zeros(len(zb), np.float32)])
    zl_all = np.concatenate([zl, zb])
    Z = torch.tensor(norm(zall)); Y = torch.tensor(Vall); E = torch.tensor(ell_all)
    ZL = torch.tensor(norm(zl_all)); M = torch.tensor(mask_res)
    ZV = torch.tensor(norm(zv)); YV = torch.tensor(Vv)
    model = MLP()
    nparam = sum(p.numel() for p in model.parameters())
    opt = torch.optim.Adam(model.parameters(), lr=LR)
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, EPOCHS, eta_min=1e-5)
    n = len(Z); log = open(out_dir / f"train_{tag}.log", "w")
    print(f"{tag}: params={nparam} n={n} lam_s={lam_s}", file=log, flush=True)
    t0 = time.time()
    for ep in range(EPOCHS):
        perm = torch.randperm(n)
        model.train(); tot = 0.0
        for i in range(0, n, BATCH):
            idx = perm[i:i + BATCH]
            w = model(Z[idx])
            loss = ((w - Y[idx]) ** 2).mean()
            if lam_s > 0:
                m = M[idx]
                if bool(m.any()):
                    wl = model(ZL[idx][m])
                    res = w[m] - E[idx][m] - wl
                    loss = loss + lam_s * (res ** 2).mean()
            opt.zero_grad(); loss.backward(); opt.step()
            tot += loss.item() * len(idx)
        sched.step()
        if ep % 10 == 9 or ep == EPOCHS - 1:
            model.eval()
            with torch.no_grad():
                wv = model(ZV)
                err = (wv - YV).abs()
            print(f"ep {ep+1} loss {tot/n:.3e} val_rmse {err.pow(2).mean().sqrt():.4e} val_linf {err.max():.4e} {time.time()-t0:.0f}s", file=log, flush=True)
    log.close()
    torch.save(model.state_dict(), out_dir / f"model_{tag}.pt")
    protocol_path = data_dir / "data_protocol.json"
    metadata = dict(params=nparam, width=WIDTH, depth=DEPTH, epochs=EPOCHS,
                    batch=BATCH, lr=LR, lam_s=lam_s, h=H,
                    n_train=int(len(z)), n_boundary=int(len(zb)),
                    terminal_boundary_supervision=terminal_boundary,
                    dataset_protocol=json.loads(protocol_path.read_text()) if protocol_path.exists() else None)
    (out_dir / f"model_{tag}.json").write_text(json.dumps(metadata, indent=2))


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("models", nargs="*", choices=["mse", "res"])
    p.add_argument("--data-dir", type=Path, default=Path("out"))
    p.add_argument("--out-dir", type=Path, default=Path("out"))
    p.add_argument("--terminal-boundary", action="store_true")
    args = p.parse_args()
    which = args.models or ["mse", "res"]
    if "mse" in which: run("mse", 0.0, args.data_dir, args.out_dir, args.terminal_boundary)
    if "res" in which: run("res", LAM_S, args.data_dir, args.out_dir, args.terminal_boundary)
